CREATE OR REPLACE VIEW v_ilb_psoriasis_keratinocyte_geometry_readiness AS
SELECT
  (SELECT COUNT(*) FROM ilb_psoriasis_keratinocyte_equation) AS equations,
  (SELECT SUM(closure_status='DERIVED') FROM ilb_psoriasis_keratinocyte_equation) AS fully_derived_equations,
  (SELECT SUM(closure_status='STRUCTURE_DERIVED') FROM ilb_psoriasis_keratinocyte_equation) AS structure_derived_equations,
  (SELECT SUM(closure_status='NOT_CLOSED') FROM ilb_psoriasis_keratinocyte_equation) AS not_closed_equations,
  (SELECT COUNT(*) FROM ilb_psoriasis_keratinocyte_primitive) AS primitives,
  (SELECT SUM(value_num IS NOT NULL) FROM ilb_psoriasis_keratinocyte_primitive) AS numeric_primitives,
  'IL17 occupancy -> signaling structure -> compartment balances -> epidermal geometry; quantitative signal-to-cycle transfer remains unresolved' AS governance_note;
