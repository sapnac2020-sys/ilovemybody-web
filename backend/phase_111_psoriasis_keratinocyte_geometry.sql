-- Phase 111: Psoriasis IL-17 -> keratinocyte population -> epidermal geometry
-- Formula-first rule: DERIVE -> PREDICT -> VERIFY. No unsourced numeric coefficients.

CREATE TABLE IF NOT EXISTS ilb_psoriasis_keratinocyte_equation (
  equation_id VARCHAR(64) PRIMARY KEY,
  equation_code VARCHAR(64) NOT NULL UNIQUE,
  layer_name VARCHAR(64) NOT NULL,
  equation_latex TEXT NOT NULL,
  derivation_class VARCHAR(64) NOT NULL,
  closure_status VARCHAR(64) NOT NULL,
  biological_basis TEXT NOT NULL,
  unresolved_primitives TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ilb_psoriasis_keratinocyte_primitive (
  primitive_code VARCHAR(64) PRIMARY KEY,
  primitive_name VARCHAR(128) NOT NULL,
  unit_text VARCHAR(64) NOT NULL,
  source_rule VARCHAR(128) NOT NULL,
  allowed_origin VARCHAR(64) NOT NULL,
  value_num DECIMAL(30,12) NULL,
  source_note TEXT NULL,
  context_requirement TEXT NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'UNRESOLVED'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

